#define GESTURE_COUNT 4

int predict_gesture(const int8_t *prediction_scores) {
	int max_prediction_index = -1;
	int8_t max_prediction_score = -128;

	for (int i = 0; i < GESTURE_COUNT; i++) {
		if ((max_prediction_index == -1) ||
			(prediction_scores[i] > max_prediction_score)) {
			max_prediction_score = prediction_scores[i];
			max_prediction_index = i;
		}
	}

	return max_prediction_index;
}

void test_gesture(const char *name, int8_t input[1][128][3][1]) {
	printf("\n=== Testing: %s ===\n", name);

	int8_t model_output[1][4];
	run_model(input, model_output);

	printf("Raw outputs (int8): [%d, %d, %d, %d]\n",
		   model_output[0][0], model_output[0][1],
		   model_output[0][2], model_output[0][3]);

	printf("Probabilities:\n");
	const char *names[] = {"Wing", "Ring", "Slope", "None"};

	/* Find max for percentage display */
	int8_t max_score = -128;
	for (int i = 0; i < 4; i++) {
		if (model_output[0][i] > max_score) {
			max_score = model_output[0][i];
		}
	}

	for (int i = 0; i < 4; i++) {
		/* Convert int8 (-128 to 127) to percentage */
		/* Normalize to 0-255 range first: (value + 128) */
		int percentage = ((model_output[0][i] + 128) * 100) / 255;
		printf("  %s: %d%% (raw: %d)\n", names[i], percentage, model_output[0][i]);
	}

	/* Use integer-only prediction */
	int detected = predict_gesture(model_output[0]);
	printf("→ Detected: %s\n", names[detected]);
}

